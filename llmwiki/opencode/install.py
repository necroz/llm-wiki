"""Install the OpenCode autosync plugin.

OpenCode has no JSON ``Stop`` hook like ZCode.  Autosync is therefore a
small server plugin that subscribes to ``session.idle`` and spawns
``llmwiki opencode autosync`` in the background.

The plugin is written to::

    ~/.config/opencode/plugins/llmwiki-autosync/index.ts

OpenCode watches that directory and loads the plugin automatically.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Optional


def _home(home: Optional[Path]) -> Path:
    return Path(home) if home is not None else Path.home()


def _python(python_exe: Optional[Path | str]) -> str:
    return str(Path(python_exe) if python_exe is not None else Path(sys.executable))


def plugin_path(home: Optional[Path] = None) -> Path:
    """Return the user-level OpenCode plugin path."""
    return (
        _home(home)
        / ".config"
        / "opencode"
        / "plugins"
        / "llmwiki-autosync"
        / "index.ts"
    )


def _plugin_content(
    *,
    python_exe: str,
    repo_root: Path,
    build: bool,
) -> str:
    build_args = '["--build"]' if build else "[]"
    python_literal = json.dumps(python_exe, ensure_ascii=False)
    repo_literal = json.dumps(str(repo_root), ensure_ascii=False)
    return f"""\
import {{ Plugin }} from "@opencode/plugin"
import {{ spawn }} from "node:child_process"

// Generated by: llmwiki opencode install
const PYTHON = {python_literal}
const REPO_ROOT = {repo_literal}
const BUILD_ARGS = {build_args}

export default Plugin.define({{
  id: "llmwiki.autosync",
  async setup(ctx) {{
    const controller = new AbortController()

    void (async () => {{
      for await (const event of ctx.event.subscribe({{ signal: controller.signal }})) {{
        if (event.type !== "session.idle") continue
        try {{
          const child = spawn(
            PYTHON,
            ["-m", "llmwiki", "opencode", "autosync", "--quiet", ...BUILD_ARGS],
            {{
              cwd: REPO_ROOT,
              detached: true,
              stdio: "ignore",
            }},
          )
          child.unref()
        }} catch {{
          // Never break the OpenCode server because autosync could not start.
        }}
      }}
    }})().catch(() => {{}})

    return () => controller.abort()
  }},
}})
"""


def install_plugin(
    *,
    home: Optional[Path] = None,
    python_exe: Optional[Path | str] = None,
    repo_root: Optional[Path] = None,
    build: bool = False,
    dry_run: bool = False,
    force: bool = False,
) -> list[str]:
    """Write the OpenCode autosync plugin. Idempotent unless ``force``."""
    path = plugin_path(home)
    if path.exists() and not force:
        return [f"plugin: already installed in {path}"]
    if dry_run:
        return [f"plugin: would write {path}"]

    py = _python(python_exe)
    root = Path(repo_root) if repo_root is not None else Path.cwd()
    content = _plugin_content(python_exe=py, repo_root=root, build=build)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return [f"plugin: installed in {path}"]


def install_all(
    *,
    home: Optional[Path] = None,
    python_exe: Optional[Path | str] = None,
    repo_root: Optional[Path] = None,
    build: bool = False,
    dry_run: bool = False,
    force: bool = False,
) -> list[str]:
    """Install the OpenCode autosync plugin."""
    return install_plugin(
        home=home,
        python_exe=python_exe,
        repo_root=repo_root,
        build=build,
        dry_run=dry_run,
        force=force,
    )
